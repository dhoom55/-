def cs_props(r):
    """Arabic is a complex script: Word uses w:szCs / w:bCs for it, not w:sz / w:b."""
    rpr = r._r.get_or_add_rPr()
    sz = rpr.find(qn("w:sz"))
    if sz is not None and rpr.find(qn("w:szCs")) is None:
        sz.addnext(rpr.makeelement(qn("w:szCs"), {qn("w:val"): sz.get(qn("w:val"))}))
    b = rpr.find(qn("w:b"))
    if b is not None and rpr.find(qn("w:bCs")) is None:
        b.addnext(rpr.makeelement(qn("w:bCs"), {}))


def rtl(p, align=None):
    ppr = p._p.get_or_add_pPr()
    if ppr.find(qn("w:bidi")) is None:
        ppr.insert_element_before(OxmlElement("w:bidi"), *PPR_AFTER_BIDI)
    for r in p.runs:
        cs_props(r)
        r._r.get_or_add_rPr().get_or_add_rtl()
    if align is not None:
        p.alignment = align
    return p


def style_fonts(doc):
    for name in ("Normal", "Title", "Heading 1", "Heading 2", "List Bullet", "List Number"):
        st = doc.styles[name]
        st.font.name = FONT
        rpr = st.element.get_or_add_rPr()
        f = rpr.get_or_add_rFonts()
        for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            f.set(qn(a), FONT)
        if name.startswith("Heading") or name == "Title":
            st.font.color.rgb = NAVY
    n = doc.styles["Normal"]
    n.font.size = Pt(12)
    rpr = n.element.get_or_add_rPr()
    sz = rpr.find(qn("w:sz"))
    if sz is not None and rpr.find(qn("w:szCs")) is None:
        sz.addnext(rpr.makeelement(qn("w:szCs"), {qn("w:val"): "24"}))
    for name, size in (("Heading 1", 16), ("Heading 2", 13)):
        doc.styles[name].font.size = Pt(size)
        r = doc.styles[name].element.get_or_add_rPr()
        s = r.find(qn("w:sz"))
        if s is not None and r.find(qn("w:szCs")) is None:
            s.addnext(r.makeelement(qn("w:szCs"), {qn("w:val"): str(size * 2)}))


def shade(cell, hex_):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_)
    tcpr.append(shd)


def para(doc, text, bold_lead=None):
    p = doc.add_paragraph()
    if bold_lead:
        p.add_run(bold_lead).bold = True
    p.add_run(text)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.25
    return rtl(p)


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        if isinstance(it, tuple):
            p.add_run(it[0]).bold = True
            p.add_run(it[1])
        else:
            p.add_run(it)
        rtl(p)


def h1(doc, text):
    return rtl(doc.add_heading(text, level=1))


def h2(doc, text):
    return rtl(doc.add_heading(text, level=2))


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblpr = t._tbl.tblPr
    tblpr.insert_element_before(OxmlElement("w:bidiVisual"), *TBLPR_AFTER_BIDI)
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.bold = True
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        rtl(c.paragraphs[0], WD_ALIGN_PARAGRAPH.CENTER)
        shade(c, HEAD_FILL)
    # repeat header row on every page
    trpr = t.rows[0]._tr.get_or_add_trPr()
    trpr.append(OxmlElement("w:tblHeader"))
    for n, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            cells[i].paragraphs[0].add_run(v)
            rtl(cells[i].paragraphs[0])
            if n % 2:
                shade(cells[i], ALT_FILL)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def header_footer(section):
    hp = section.header.paragraphs[0]
    hp.text = ""
    r = hp.add_run("الأمن والحماية لوحدات رابغ  |  التصنيف: ............ (تحدده الجهة المختصة)")
    r.font.size = Pt(9)
    r.font.color.rgb = RGBColor(0x6B, 0x8A, 0xA3)
    rtl(hp, WD_ALIGN_PARAGRAPH.CENTER)
    fp = section.footer.paragraphs[0]
    fp.text = ""
    run = fp.add_run("صفحة ")
    run.font.size = Pt(9)
    r2 = fp.add_run()
    for kind, txt in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = txt
        r2._r.append(el)
    r2.font.size = Pt(9)
    rtl(fp, WD_ALIGN_PARAGRAPH.CENTER)


def cover(doc):
    for _ in range(5):
        doc.add_paragraph()
    p = doc.add_paragraph()
    r = p.add_run("خطة تطوير الأمن والحماية\nوقطاعات الدفاع الجوي")
    r.bold = True
    r.font.size = Pt(28)
    r.font.color.rgb = NAVY
    rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
    p = doc.add_paragraph()
    r = p.add_run("وحدات رابغ")
    r.font.size = Pt(20)
    r.font.color.rgb = RGBColor.from_string(GOLD)
    rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
    doc.add_paragraph()
    for line in ("الإصدار: 1.0 (مسودة للمراجعة)",
                 "تاريخ الإعداد: ........ / ........ / ........",
                 "أعدّها: ................................",
                 "اعتمدها: ................................",
                 "التصنيف: ................ (تحدده الجهة المختصة)"):
        p = doc.add_paragraph()
        p.add_run(line).font.size = Pt(13)
        rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
    doc.add_page_break()


